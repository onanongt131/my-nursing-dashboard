/**
 * จัดกลุ่มสาเหตุ AMA จากข้อความที่หอพิมพ์เอง (ช่องสาเหตุเป็นข้อความอิสระ)
 * ตรวจตามลำดับ: ไปรักษาที่อื่น ก่อน กลับบ้าน เพราะ "ญาติต้องการพาไปรักษา รพ.ใกล้บ้าน" ควรเป็นไปรักษาที่อื่น
 */
const RULES: [string, RegExp][] = [
  ['ไปรักษาที่อื่น (รพ.ใกล้บ้าน / ต่างจังหวัด / เอกชน)', /เอกชน|โรงพยาบาล|(^|[^ก-๙])รพ\.|(^|\s)รพ(\s|$)|คลินิก|ต่างจังหวัด|ใกล้บ้าน|รักษาต่อ|ไปรักษา|ส่งตัว|refer/i],
  ['ค่าใช้จ่าย / สิทธิการรักษา', /ค่าใช้จ่าย|ค่ารักษา|เงิน|สิทธิ|ไม่มีค่า|จ่าย/],
  ['ไม่มีผู้ดูแล / ภาระครอบครัว / งาน', /ดูแล|ภาระ|ลูก|ทำงาน|งาน|ธุระ|ครอบครัว/],
  ['ไม่พึงพอใจบริการ', /ไม่พอใจ|ไม่พึงพอใจ|บริการ|รอนาน/],
  ['ต้องการกลับบ้าน', /กลับบ้าน|ไม่อยากอยู่|อยากกลับ|ไม่ประสงค์|ปฏิเสธการรักษา|ไม่ต้องการรักษา/],
];

export function amaReasonCategory(reason: unknown): string {
  const t = typeof reason === 'string' ? reason.trim() : '';
  if (!t) return 'ไม่ระบุสาเหตุ';
  return RULES.find(([, re]) => re.test(t))?.[0] ?? 'อื่น ๆ';
}

/** ผู้แสดงความประสงค์: ญาติ หรือ ผู้ป่วย (ถ้าระบุในข้อความ) */
export function amaRequester(reason: unknown): string | null {
  const t = typeof reason === 'string' ? reason : '';
  if (/ญาติ|ครอบครัว|บุตร|ลูก|สามี|ภรรยา|มารดา|บิดา/.test(t)) return 'ญาติ';
  if (/ผู้ป่วย/.test(t) && !/ญาติ/.test(t)) return 'ผู้ป่วย';
  return null;
}
